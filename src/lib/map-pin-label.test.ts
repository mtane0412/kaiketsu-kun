/**
 * 地図のピンに表示するラベル（証言の順番）の組み立てのテスト
 */
import { describe, expect, it } from 'vitest';
import { pinLabel } from './map-pin-label';

describe('pinLabel', () => {
  it('順番が3つ以下の場合は、すべての順番を「・」でつないで表示する', () => {
    // 前提: 同じ場所を述べる証言が3件ある
    // 検証: 3つの順番がすべて表示される
    expect(pinLabel([1, 3, 5], 7)).toBe('1・3・5');
  });

  it('順番が4つ以上あり、選択中の証言がない場合は、先頭の3つと残りの件数を表示する', () => {
    // 前提: 同じ場所を述べる証言が5件あり、選択中の証言は別の場所にある
    // 検証: 先頭の3つの順番と「他2件」が表示され、ラベルが際限なく伸びない
    expect(pinLabel([2, 4, 6, 8, 10], 1)).toBe('2・4・6 他2件');
  });

  it('順番が4つ以上あり、選択中の証言がある場合は、選択中の順番とピン内での位置を表示する', () => {
    // 前提: 同じ場所を述べる証言が5件あり、そのうち4件目（順番8）を選択している
    // 検証: 選択中の順番が隠れず、ピン内の何件目かが分かる
    expect(pinLabel([2, 4, 6, 8, 10], 8)).toBe('8（5件中4件目）');
  });

  it('順番が3つ以下の場合は、選択中の証言があってもすべての順番を表示する', () => {
    // 前提: 証言が2件あり、そのうち順番4を選択している
    // 検証: 件数が少ないため、通常どおりすべての順番が表示される
    expect(pinLabel([2, 4], 4)).toBe('2・4');
  });

  it('順番がちょうど3つの場合は、選択中の証言があってもすべての順番を表示する', () => {
    // 前提: 証言が上限と同じ3件あり、そのうち順番3を選択している
    // 検証: 上限ちょうどではまとめずに、すべての順番が表示される
    expect(pinLabel([1, 2, 3], 3)).toBe('1・2・3');
  });

  it('順番がちょうど4つの場合は、まとめて表示する', () => {
    // 前提: 証言が上限を1つ超える4件あり、選択中の証言は別の場所にある
    // 検証: 上限を1つでも超えると、先頭の3つと「他1件」にまとめられる
    expect(pinLabel([1, 2, 3, 4], 9)).toBe('1・2・3 他1件');
  });
});
