/**
 * ドメインモデルの型定義（検証用ドラフト）
 *
 * このファイルは、調査ボードが扱う一次データの形を定義します。
 * 設計の中心は「主張（Claim）」です。人物相関図・時系列・証言者別・地図の各ビューは、
 * すべて主張と出来事の集合から導出される表示であり、一次データではありません。
 *
 * 用語:
 * - 案件（Case）: 1つの事件、または1つの作品。すべてのデータの入れ物
 * - 人物（Person）: 発言しうる主体の全般。個人・組織・記録装置に加えて、新聞や書籍などの媒体も含む
 * - 主張（Claim）: 「誰が・誰を経由して・何を述べたか」の1単位。証言とユーザーの推測の総称
 * - 出来事（Event）: 同じ事柄についての主張を束ねるラベル。日時・場所は束ねた主張から導出する
 * - 時刻参照（TimeRef）: 曖昧さを許す時刻の表現
 *
 * 注意: このファイルは実データで書き起こして破綻しないかを確かめるためのドラフトです。
 * 未決事項は docs/domain-model.md に記載しています。
 */

/** 各エンティティを一意に識別するID（nanoidで生成する想定）です。 */
export type Id = string;

/**
 * 曖昧さを許す時刻の表現です。
 *
 * 「1995年7月頃」「17年前」「第3話」のように、資料に現れる時刻は精度がばらばらです。
 * そのため、原文表記を必ず保持し、機械的に並べるための情報を任意で添える形にしています。
 *
 * - 実在の日時が分かる場合: earliest と latest に区間を入れます。
 *   例「1995年7月頃」→ earliest: '1995-06-01', latest: '1995-08-31'
 * - 実在の日時が無い場合（作中の時系列や話数など）: order に並び順の数値を入れます。
 *
 * 注意: 時系列ボード上の位置は、時刻参照ではなく案件の並び順（Case.timelineOrder）で決まります。
 * order は、述べられた時点（Claim.statedAt）の並べ替えに使用します。
 */
export type TimeRef = {
  /** 資料に書かれていた通りの表記です。 */
  text: string;
  /**
   * 取り得る最も早い時点です。精度に応じたISO 8601の部分表記で指定します
   * （'1998' / '1998-08' / '1998-08-12' / '1998-08-12T19:00'）。
   */
  earliest?: string;
  /**
   * 取り得る最も遅い時点です。表記の形式は earliest と同じです。
   * 省略した場合は、earliest が表す期間の終わり（'1998' なら1998年末）までの区間として扱います。
   */
  latest?: string;
  /** 実在の日時が無い場合の並び順です。小さいほど先に並びます。 */
  order?: number;
};

/**
 * 案件に登場する人物です。
 *
 * 個人だけでなく、組織（警察など）・記録装置（防犯カメラなど）・媒体（新聞、書籍、調書など）を含む、
 * 発言しうる主体の全般を表します。以前の版では媒体を「ソース」という別の種類で持っていましたが、
 * 「新聞が報じた」も「警察が発表した」も同じ「誰かがそう述べた」であるため、人物に統合しました。
 * 個人・組織・記録装置・媒体を区別する項目は持ちません。名前で区別がつき、区別によって動作が変わる処理が無いためです。
 * 補足が必要な場合は note に書きます。
 */
export type Person = {
  id: Id;
  name: string;
  /** 別名・旧姓・偽名などです。 */
  aliases?: string[];
  imageDataUrl?: string;
  note?: string;
};

/** 案件に登場する場所です。緯度経度は地図ビューを作る段階で使用します。 */
export type Place = {
  id: Id;
  name: string;
  latitude?: number;
  longitude?: number;
  note?: string;
};

/**
 * 同じ事柄についての主張を束ねるラベルです。
 *
 * 出来事は、日時・場所・関与人物を自分では持ちません。未解決事件では、警察発表の時系列も含めて
 * すべての出来事が誰かの主張であり、特定の見立てを基準に置くと比較が偏るためです。
 * 出来事のボード上の位置・場所・言及されている人物は、束ねた主張から導出します（src/domain/case-views.ts）。
 * ユーザー自身の見立ては、発言者が 'user' の主張として、他の主張と同列に記述します。
 */
export type Event = {
  id: Id;
  title: string;
  /** 出来事についてのメモです。 */
  description?: string;
};

/**
 * 主張を述べた主体です。
 *
 * - person: 人物の発言。複数人が同じことを述べたと伝えられている場合は、全員を personIds に持ちます（1人以上）。
 *   別の経路や別の時点でそれぞれが述べた場合は、独立した裏付けかどうかを比べられるよう、別々の主張にします。
 *   報道の地の文や漫画のナレーションは、その媒体（人物として登録します）の発言です。
 * - user: ユーザー自身の推測
 */
export type Speaker = { kind: 'person'; personIds: Id[] } | { kind: 'user' };

/**
 * 「誰が・誰を経由して・何を述べたか」の1単位です。
 *
 * 証言とユーザーの推測は同じ型で表し、speaker の違いで区別します。
 */
export type Claim = {
  id: Id;
  speaker: Speaker;
  /**
   * 発言者の発言をユーザーに伝えた人物です。伝えた順に並べ、最後の要素がユーザーが直接見聞きした相手です。
   * 例「Aが自供したと警察の調書にある」→ speaker: A、viaPersonIds: [警察の調書]
   * 例「防犯カメラに映っていたと県警が発表したと新聞が報じた」→ speaker: 防犯カメラ、viaPersonIds: [県警, 新聞]
   * 発言者から直接見聞きした場合と、ユーザーの推測では、空の配列です。
   * 経由を残すのは、複数の主張が独立した裏付けなのか、同じ経路から出た1つの情報なのかを判断するためです。
   */
  viaPersonIds: Id[];
  /**
   * 資料内の位置です（ページ番号、話数、動画のタイムスタンプなど）。
   * 注意: 入力欄は廃止しました。以前の版で入力された値を失わないために保持している項目です。
   */
  locator?: string;
  /**
   * 本文を要約する見出しです。本文が長い主張を、ボードや一覧で見分けやすくするために付けます。
   * 注意: メンションには対応していません。出来事・場所・言及している人物は、本文（content）からだけ導出します。
   */
  title?: string;
  /** 述べられた内容です。 */
  content: string;
  /** この主張が述べられた時点です。出来事が起きた時点とは別の時間軸です。 */
  statedAt?: TimeRef;
  /** この主張が対象とする出来事です。人物評のように出来事を伴わない主張では省略します。 */
  eventId?: Id;
  /** この主張が言及している人物です。 */
  mentionedPersonIds: Id[];
  /**
   * この主張が述べる出来事の日時です。時系列ボード上の位置は決めませんが、
   * 日時と矛盾する位置には並べられません（src/domain/timeline-order.ts）。
   * 同じ出来事に束ねた他の主張と食い違う場合があります。
   */
  when?: TimeRef;
  /** この主張が述べる出来事の場所です。同じ出来事に束ねた他の主張と食い違う場合があります。 */
  placeId?: Id;
};

/**
 * 人物間の関係です。
 *
 * 関係はユーザーが主張から導いた結論として扱い、根拠となる主張を basisClaimIds で参照します。
 * basisClaimIds が空の関係は「根拠未登録」として表示上区別します。
 */
export type Relationship = {
  id: Id;
  fromPersonId: Id;
  toPersonId: Id;
  label: string;
  /** true の場合は from から to への片方向、false の場合は双方向の関係です。 */
  directed: boolean;
  basisClaimIds: Id[];
};

/** 1つの事件、または1つの作品を表す入れ物です。 */
export type Case = {
  id: Id;
  name: string;
  persons: Person[];
  places: Place[];
  events: Event[];
  claims: Claim[];
  relationships: Relationship[];
  /**
   * 時系列ボードの項目（出来事の束、出来事に束ねていない主張）の並び順です。
   * 要素は 'event:出来事のID' または 'claim:主張のID' の形のキーです。
   * 載っていない項目は末尾に並べ、ボードの項目ではなくなったキーは無視します（src/domain/timeline-order.ts）。
   */
  timelineOrder: string[];
};
